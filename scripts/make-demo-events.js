#!/usr/bin/env node
/* Writes the shipped example events.json containing ONLY fictional, clearly-labelled DEMO events.
   The first real weekly run of scripts/update-events.js overwrites it. */
'use strict';
const fs = require('fs'), path = require('path');
const Core = require('../core.js'), Demo = require('../demo-data.js');
const events = Core.sortEvents(Core.dedupe(Demo.build()));
const meta = { version: 1, generatedAt: new Date().toISOString(), generatedBy: 'scripts/make-demo-events.js', demo: true,
  note: 'DEMO DATA — fictional sample events. Replaced by real data after the first run of scripts/update-events.js.',
  refreshEveryDays: 7, eventCount: events.length, sourcesOk: 0, sourcesFailed: 0, sources: {} };
fs.writeFileSync(path.join(__dirname, '..', 'events.json'), JSON.stringify({ meta, events }, null, 1));
fs.writeFileSync(path.join(__dirname, '..', 'events-data.js'), '/* generated by scripts/update-events.js. Empty until the first real update. */\nwindow.GTA_EVENTS_DATA = null;\n');
console.log('Wrote demo events.json with ' + events.length + ' events');
